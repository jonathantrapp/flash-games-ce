"""Extract the original stage titles and briefing text from LevelTip.as into src/tips.h."""
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent
source = (HERE / 'original/scripts/xplor/Menus/LevelTip.as').read_text()
block = source[source.index('public var levelTip:Array'):source.index('public var words:Array')]
entries = re.split(r'new Array\(\s*(?:SPECIAL|BEWARE|NONE)\s*,\s*\d+\s*,', block)[1:]
assert len(entries) == 17, len(entries)

def decode(literal: str) -> str:
    out, i = [], 0
    while i < len(literal):
        ch = literal[i]
        if ch == '\\' and i + 1 < len(literal):
            nxt = literal[i + 1]
            out.append({'n': '\n', "'": "'", '"': '"', '\\': '\\'}.get(nxt, nxt))
            i += 2
        else:
            out.append(ch)
            i += 1
    return ''.join(out)

titles, texts = [], []
for entry in entries:
    strings = [decode(s) for s in re.findall(r'"((?:[^"\\]|\\.)*)"', entry)]
    titles.append(strings[0])
    texts.append(''.join(strings[1:]))

def c_string(text: str) -> str:
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'

lines = ['/* Generated by generate_tips.py from the original LevelTip.as. */',
         '#ifndef SCOUT_TIPS_H', '#define SCOUT_TIPS_H',
         'static const char *const stageTitles[17]={' + ','.join(c_string(t) for t in titles) + '};',
         'static const char *const stageTips[17]={']
lines += [c_string(t) + ',' for t in texts]
lines += ['};', '#endif', '']
(HERE / 'src/tips.h').write_text('\n'.join(lines), encoding='utf-8')
print('titles:', titles)
print('tip bytes:', sum(len(t) for t in texts))
