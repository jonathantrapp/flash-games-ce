"""Pack the many small PDG/PDLV/UI resources into a few archived bank AppVars.

Run after build_assets.py and build_full_assets.py. Each bank is at most 32 KB so two share one 64 KB flash sector (60 KB banks made the
emulator USB transfer stall). The C side finds a resource by name through src/bundle.h, so game code is unchanged.
Fewer files also makes the calculator transfer and emulator transfer much faster.
"""
from pathlib import Path
import re
import subprocess
import hashlib
import struct

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
CONV = ROOT / 'local-tools/cedev/CEdev/bin/convbin.exe'
LIMIT = 32000
HEADER = 11
UI_NAMES = ['PDHEART', 'PDMAIL', 'PDFURY', 'PDFURYI', 'PDFBOX', 'PDXP', 'PDBADG', 'PDBADGI', 'PDSKI', 'PDSKF', 'PDSKT', 'PDSKP', 'PDSKB']

names = sorted(p.stem for p in (HERE / 'data').glob('PDG[0-9][0-9].bin')) + sorted(p.stem for p in (HERE / 'data').glob('PDLV[0-9][0-9].bin')) + UI_NAMES + ['PDBLIMP0', 'PDBLIMP1', 'PDBOOM']
blobs = {n: (HERE / 'data' / (n + '.bin')).read_bytes() for n in names}
assert all(0 < len(b) <= LIMIT-HEADER for b in blobs.values()), [n for n, b in blobs.items() if len(b) > LIMIT-HEADER]
signature = hashlib.sha256(b''.join(n.encode('ascii') + b'\0' + struct.pack('<I', len(blobs[n])) + blobs[n] for n in sorted(blobs))).digest()[:8]

banks, entries = [], {}
for name in sorted(blobs, key=lambda n: -len(blobs[n])):          # first-fit decreasing
    for index, bank in enumerate(banks):
        if len(bank) + len(blobs[name]) <= LIMIT-HEADER:
            break
    else:
        banks.append(bytearray())
        index = len(banks) - 1
    entries[name] = (index, HEADER + len(banks[index]), len(blobs[name]))
    banks[index] += blobs[name]

for stale in list((HERE / 'bin').glob('PDB[0-9][0-9].8xv')):
    stale.unlink()
bank_sizes = []
for index, bank in enumerate(banks):
    name = f'PDB{index:02d}'
    source = HERE / 'data' / (name + '.bin')
    size = HEADER + len(bank)
    bank_sizes.append(size)
    source.write_bytes(signature + bytes([index]) + struct.pack('<H', size) + bytes(bank))
    subprocess.run([str(CONV), '-j', 'bin', '-k', '8xv', '-r', '-n', name, '-i', str(source), '-o', str(HERE / 'bin' / (name + '.8xv'))],
                   check=True, stdout=subprocess.DEVNULL)
for name in names + ['PDACTOR']:                                    # the bundled and obsolete individual AppVars
    path = HERE / 'bin' / (name + '.8xv')
    if path.exists():
        path.unlink()

lines = ['/* Generated by bundle_assets.py. Resource name -> bank AppVar, offset and size. */', '#ifndef BUNDLE_H', '#define BUNDLE_H',
         f'#define BUNDLE_BANKS {len(banks)}',
         'static const uint8_t bundle_signature[8]={' + ','.join(map(str,signature)) + '};',
         'static const uint16_t bundle_bank_sizes[]={' + ','.join(map(str,bank_sizes)) + '};',
         'typedef struct { const char *name; unsigned char bank; unsigned short offset, size; } BundleEntry;',
         'static const BundleEntry bundle[] = {']
lines += ['{"%s",%d,%d,%d},' % (n, *entries[n]) for n in sorted(entries)]
lines += ['};', '#endif', '']
(HERE / 'src/bundle.h').write_text('\n'.join(lines), encoding='utf-8')
print(f'{len(names)} resources packed into {len(banks)} banks:', [len(b) for b in banks])
