"""Store each distinct nonuniform original sky row once for RAM row copies."""
from pathlib import Path
import hashlib,json
HERE=Path(__file__).resolve().parent
a=(HERE/'data/PDU20.bin').read_bytes();b=(HERE/'data/PDU21.bin').read_bytes()
assert a[:2]==b[:2]==bytes([160,240])
rows=[a[2+y*160:2+(y+1)*160]+b[2+y*160:2+(y+1)*160] for y in range(240)]
unique=[];ids=[];colors=[]
for row in rows:
 assert len(row)==320
 colors.append(row[0])
 if len(set(row))==1:ids.append(255)
 else:
  if row not in unique:unique.append(row)
  ids.append(unique.index(row))
assert len(unique)<255
# Join overlapping row suffixes/prefixes. Every indexed row stays contiguous,
# so the runtime still performs one exact row copy, without decompression.
edges=[]
for i,x in enumerate(unique):
 for j,y in enumerate(unique):
  if i!=j:edges.append((next((k for k in range(319,0,-1) if x[-k:]==y[:k]),0),i,j))
following={};preceding={};parent=list(range(len(unique)))
def find(n):
 while parent[n]!=n:n=parent[n]
 return n
for overlap,i,j in sorted(edges,reverse=True):
 if overlap and i not in following and j not in preceding and find(i)!=find(j):
  following[i]=(j,overlap);preceding[j]=i;parent[find(i)]=find(j)
pixels=bytearray()
for start in range(len(unique)):
 if start in preceding:continue
 pixels+=unique[start];i=start
 while i in following:i,overlap=following[i];pixels+=unique[i][overlap:]
assert len(pixels)<65535
offsets=[65535 if id==255 else pixels.find(unique[id]) for id in ids]
assert all(v>=0 for v in offsets)
decoded=b''.join(bytes([colors[y]])*320 if offsets[y]==65535 else pixels[offsets[y]:offsets[y]+320] for y in range(240))
assert decoded==b''.join(rows)
lines=['/* Lossless original sky rows; generated by build_row_sky.py. */',
 '#define SKY_ROW_BYTES '+str(len(pixels)),
 'static const uint16_t sky_row_offsets[240]={'+','.join(map(str,offsets))+'};',
 'static const uint8_t sky_row_colors[240]={'+','.join(map(str,colors))+'};',
 '#ifndef SKY_FLASH_ROWS','static const uint8_t sky_row_pixels[]={']
lines+=[','.join(map(str,pixels[i:i+48]))+',' for i in range(0,len(pixels),48)]
lines+=['};','#endif','']
(HERE/'src/sky_rows.h').write_text('\n'.join(lines))
result=dict(unique_nonuniform_rows=len(unique),pixel_storage_bytes=len(pixels),overlap_bytes_saved=len(unique)*320-len(pixels),index_bytes=720,pixels_compared=len(decoded),original_sha256=hashlib.sha256(decoded).hexdigest())
(HERE/'tests/row-sky-results.json').write_text(json.dumps(result,indent=2)+'\n');print(json.dumps(result))
